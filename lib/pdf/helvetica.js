const WIDTHS = { regular: REGULAR, bold: BOLD };

function textWidth(text, font, size) {
  const widths = WIDTHS[font];
  const units = encodeWinAnsi(text).reduce((sum, code) => sum + (widths[code - 32] ?? 556), 0);
  return (units * size) / 1000;
}

// Lines no wider than maxWidth, broken at spaces; a word longer than a line is
// cut wherever it has to be. Line breaks in the text are kept.
function wrapText(text, font, size, maxWidth) {
  const lines = [];
  for (const paragraph of String(text).split(/\r?\n/)) {
    let line = '';
    for (const word of paragraph.split(' ')) {
      const candidate = line ? `${line} ${word}` : word;
      if (textWidth(candidate, font, size) <= maxWidth) {
        line = candidate;
        continue;
      }
      if (line) {
        lines.push(line);
      }
      line = word;
      while (textWidth(line, font, size) > maxWidth && line.length > 1) {
        let cut = line.length - 1;
        while (cut > 1 && textWidth(line.slice(0, cut), font, size) > maxWidth) {
          cut -= 1;
        }
        lines.push(line.slice(0, cut));
        line = line.slice(cut);
      }
    }
    lines.push(line);
  }
  return lines;
}

module.exports = { textWidth, wrapText };
